def half_at(py):
    return 128 * (1 - abs(py - 214) / 64)

bad = []
for (x, y, w, h, name) in RECTS:
    # 矩形四角 + 每行最大半寬檢查（矩形可能跨菱形不同段）
    for py in range(y, y + h):
        hw = half_at(py)
        if py < 150 or py > 278:
            bad.append((name, x, y, w, h, 'py超範圍 %d' % py))
            break
        if abs(x - AX) > hw + TOL or abs((x + w - 1) - AX) > hw + TOL:
            bad.append((name, x, y, w, h, 'py=%d 半寬%d x[%d..%d]' % (py, hw, x, x + w - 1)))
            break

if bad:
    print('FAIL %d 個元素超菱形（±%dpx 容差）：' % (len(bad), TOL))
    for b in bad:
        print('  ', b)
    sys.exit(1)
print('ALL %d 元素在 4×4 footprint 菱形內（±%dpx 容差）' % (len(RECTS), TOL))
